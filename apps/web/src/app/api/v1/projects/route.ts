import { z } from "zod";
import { route, body, ok, requireUser, ApiError } from "@/lib/api";
import { db } from "@/lib/db";
import { assertCanCreateProject } from "@/lib/limits";
import { parseConfig, uniquePackageName } from "@/lib/projects";
import type { Prisma } from "@prisma/client";

export const GET = route(async () => {
  const user = await requireUser();
  const projects = await db.project.findMany({
    where: { userId: user.id, status: { not: "ARCHIVED" } },
    orderBy: { updatedAt: "desc" },
    select: {
      id: true, name: true, packageName: true, category: true, status: true, updatedAt: true, createdAt: true, config: true,
      builds: { orderBy: { queuedAt: "desc" }, take: 1, select: { id: true, status: true, type: true, queuedAt: true } },
    },
  });
  return ok({
    projects: projects.map(({ config, ...p }) => {
      const c = config as { theme?: { primary?: string }; branding?: { iconUrl?: string } };
      return { ...p, primary: c.theme?.primary ?? "#6D28D9", iconUrl: c.branding?.iconUrl ?? null, lastBuild: p.builds[0] ?? null, builds: undefined };
    }),
  });
});

const createSchema = z.object({
  name: z.string().trim().min(1).max(50),
  templateId: z.string().max(64).optional(),
  /** Full config (e.g. generated by the AI assistant). */
  config: z.unknown().optional(),
});

export const POST = route(async (req) => {
  const user = await requireUser();
  const data = await body(req, createSchema);
  await assertCanCreateProject(user.id, user.planCode);

  let base: unknown;
  let category = "blank";
  if (data.config) {
    base = data.config;
    category = "ai";
  } else {
    const tpl = await db.template.findFirst({ where: { id: data.templateId ?? "blank", active: true } });
    if (!tpl) throw new ApiError(404, "Plantilla no encontrada");
    base = tpl.config;
    category = tpl.category;
  }
  const cfg = parseConfig(base);
  cfg.meta.name = data.name;
  cfg.meta.packageName = await uniquePackageName(user.id, data.name);
  const config = parseConfig(cfg);

  const project = await db.project.create({
    data: {
      userId: user.id,
      name: config.meta.name,
      packageName: config.meta.packageName,
      category,
      templateId: data.templateId ?? null,
      config: config as unknown as Prisma.InputJsonValue,
    },
  });
  return ok({ project }, 201);
});
